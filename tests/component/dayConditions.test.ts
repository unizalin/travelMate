import { flushPromises, mount } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import DayConditions from '@/components/trip/DayConditions.vue'
const mocks = vi.hoisted(() => ({ load: vi.fn() }))
vi.mock('@/services/tripWeatherService', () => ({ loadDayForecast: mocks.load }))
const day = { date: '2026-10-30', temperatureMin: 1, temperatureMax: 6, apparentMin: -3, apparentMax: 3, precipitation: 4, precipitationProbability: 60, snowfall: 0, wind: 9, gusts: 17, sunrise: '2026-10-30T09:10', sunset: '2026-10-30T17:10' }
const result = () => ({ kind: 'forecast', day, fetchedAt: new Date().toISOString() })
beforeEach(() => { mocks.load.mockReset(); mocks.load.mockResolvedValue(result()) })
afterEach(() => vi.useRealTimers())

describe('Daily weather and outfit card', () => {
  it('shows sourced weather, daylight and explicitly suggested preparation', async () => {
    const wrapper = mount(DayConditions, { props: { date: '2026-10-30', activityNames: ['Blue Lagoon'] } })
    await flushPromises()
    expect(wrapper.text()).toContain('1–6°C')
    expect(wrapper.text()).toContain('風 9 m/s')
    expect(wrapper.text()).toContain('陣風 17 m/s')
    expect(wrapper.text()).toMatch(/日出 \d{2}:\d{2}.*日落 \d{2}:\d{2}/)
    expect(wrapper.text()).toMatch(/藍調 \d{2}:\d{2}–\d{2}:\d{2}／\d{2}:\d{2}–\d{2}:\d{2}/)
    expect(wrapper.text()).toContain('白天 8 小時')
    expect(wrapper.text()).toContain('今日穿搭')
    expect(wrapper.find('.weather-line').text()).toContain('日出')
    expect(wrapper.find('.weather-line').text()).toContain('日落')
    expect(wrapper.find('.weather-line').text()).toContain('藍調')
    expect(wrapper.find('.outfit').text()).toContain('抵達日以取車、採買、休息為主')
    expect(wrapper.text()).toContain('泳衣')
    expect(wrapper.text()).toContain('以業者通知為準')
    expect(wrapper.text()).toContain('Open-Meteo')
    wrapper.unmount()
  })
  it('clears the old forecast while changing date and ignores its late response', async () => {
    let finishOld: (value: ReturnType<typeof result>) => void = () => {}
    mocks.load.mockImplementationOnce(() => new Promise(resolve => { finishOld = resolve }))
    mocks.load.mockResolvedValueOnce({ kind: 'unavailable', fetchedAt: new Date().toISOString() })
    const wrapper = mount(DayConditions, { props: { date: '2026-10-30', activityNames: [] } })
    await wrapper.setProps({ date: '2026-11-07' })
    await flushPromises()
    finishOld(result())
    await flushPromises()
    expect(wrapper.text()).toContain('來源尚未提供這一天')
    expect(wrapper.text()).not.toContain('1–6°C')
    expect(wrapper.text()).toContain('離開日：Blue Lagoon 泳衣隨身，保暖外層')
    expect(mocks.load.mock.lastCall?.[0].region.id).toBe('keflavik')
    wrapper.unmount()
  })
  it('withdraws outfit advice when the forecast is stale', async () => {
    vi.useFakeTimers()
    vi.setSystemTime(new Date('2026-10-19T12:00:00Z'))
    mocks.load.mockResolvedValue(result())
    const wrapper = mount(DayConditions, { props: { date: '2026-10-30', activityNames: [] } })
    await flushPromises()
    expect(wrapper.text()).toContain('保暖底層')
    await vi.advanceTimersByTimeAsync(31 * 60_000)
    expect(wrapper.text()).toContain('資料超過 30 分鐘')
    expect(wrapper.text()).toContain('抵達日以取車、採買、休息為主')
    wrapper.unmount()
  })
  it('falls back to non-forecast clothing guidance after a failed request', async () => {
    mocks.load.mockRejectedValue(new Error('暫時無法連線'))
    const wrapper = mount(DayConditions, { props: { date: '2026-10-30', activityNames: [] } })
    await flushPromises()
    expect(wrapper.find('[role="alert"]').text()).toContain('暫時無法連線')
    expect(wrapper.text()).not.toContain('1–6°C')
    expect(wrapper.text()).toContain('抵達日以取車、採買、休息為主')
    expect(wrapper.text()).not.toContain('預報有降水')
    wrapper.unmount()
  })
})

import test from 'node:test'
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'

const migrationPath = new URL('../../supabase/migrations/20261013020000_tripbook_journey_staging.sql', import.meta.url)
const photoMigrationPath = new URL('../../supabase/migrations/20261015050000_tripbook_photo_preferences.sql', import.meta.url)
const memoMigrationPath = new URL('../../supabase/migrations/20261015030000_tripbook_shared_memos.sql', import.meta.url)
const packingMigrationPath = new URL('../../supabase/migrations/20261016060000_tripbook_packing_checklist.sql', import.meta.url)
const packingTemplateMigrationPath = new URL('../../supabase/migrations/20261016061000_tripbook_packing_template_access.sql', import.meta.url)
const packingDepartureMigrationPath = new URL('../../supabase/migrations/20261021010000_tripbook_packing_departure_category.sql', import.meta.url)

test('journey migration defines a private RLS table and authenticated RPC surface', async () => {
  const sql = `${await readFile(migrationPath, 'utf8')}\n${await readFile(memoMigrationPath, 'utf8')}`

  assert.match(sql, /create table if not exists public\.tripbook_journeys/i)
  assert.match(sql, /owner_id uuid not null references auth\.users/i)
  assert.match(sql, /create table if not exists public\.tripbook_journey_access/i)
  assert.match(sql, /role text not null check \(role in \('editor', 'member'\)\)/i)
  assert.match(sql, /tripbook_journeys_owner_immutable/i)
  assert.match(sql, /insert into public\.trips \(id, name, destination, start_date, end_date, created_by\)/i)
  assert.match(sql, /alter table public\.tripbook_journeys enable row level security/i)
  assert.match(sql, /revoke all on table public\.tripbook_journeys from public/i)
  assert.match(sql, /grant select on table public\.tripbook_journeys to authenticated/i)
  assert.match(sql, /create policy tripbook_journeys_member_read/i)
  assert.match(sql, /using \(public\.tripbook_can_read\(trip_id\)\)/i)
  assert.match(sql, /journey\.owner_id = auth\.uid\(\)/i)
  assert.match(sql, /security definer\s+set search_path = pg_catalog, public, extensions/i)
  assert.match(sql, /create or replace function public\.tripbook_create_journey/i)
  assert.match(sql, /create or replace function public\.tripbook_load_journey/i)
  assert.match(sql, /create or replace function public\.tripbook_save_journey/i)
  assert.match(sql, /create or replace function public\.tripbook_save_journey_memo/i)
  assert.match(sql, /p_activity_id/i)
  assert.match(sql, /p_content/i)
  assert.match(sql, /clock_timestamp\(\)/i)
  assert.match(sql, /memos/i)
  assert.match(sql, /create or replace function public\.tripbook_grant_journey_access/i)
  assert.match(sql, /revoke all on function public\.tripbook_create_journey/i)
  assert.match(sql, /revoke all on function public\.tripbook_load_journey/i)
  assert.match(sql, /revoke all on function public\.tripbook_save_journey/i)
  assert.match(sql, /grant execute on function public\.tripbook_save_journey[^(]*\([^)]*\) to authenticated/i)
  assert.match(sql, /grant execute on function public\.tripbook_save_journey_memo[^(]*\([^)]*\) to authenticated/i)
  assert.match(sql, /revoke all on table public\.tripbook_journey_access from public/i)
  assert.match(sql, /revoke all on function public\.tripbook_grant_journey_access/i)
  assert.match(sql, /grant execute on function public\.tripbook_grant_journey_access[^(]*\([^)]*\) to authenticated/i)
  assert.match(sql, /journey\.owner_id = auth\.uid\(\)/i)
  assert.match(sql, /access\.role in \('editor', 'member'\)/i)
  assert.doesNotMatch(sql, /alter table public\.trip_members[\s\S]{0,240}add constraint/i)
  assert.doesNotMatch(sql, /drop constraint[^;]*trip_members/i)
  assert.match(sql, /journey_conflict/i)
  assert.match(sql, /p_expected_revision/i)
  assert.match(sql, /account_binding_unavailable/i)
  assert.match(sql, /tripbook_assert_local_point/i)
  assert.match(sql, /ambiguous local time/i)
  assert.match(sql, /arrival precedes departure/i)
  assert.match(sql, /not \(v_transport -> v_key \? 'localTime'\)/i)
  assert.match(sql, /room IDs must be unique/i)
  assert.match(sql, /benefits must contain strings/i)
  assert.match(sql, /v_order <> trunc\(v_order\)/i)
  assert.match(sql, /tripbook_assert_stamp_order/i)
  assert.match(sql, /tripbook_normalize_journey/i)
  assert.match(sql, /jsonb_typeof\(v_memo -> 'content'\) is distinct from 'string'/i)
  assert.match(sql, /jsonb_set\(v_result, '\{memos\}', '\{\}'::jsonb, true\)/i)
  assert.match(sql, /updatedBy.*v_user_id::text/i)
  assert.match(sql, /updatedAt.*clock_timestamp\(\)/i)
  assert.match(sql, /if v_user_id is null then raise exception.*not_authenticated/i)
  assert.match(sql, /if not public\.tripbook_can_edit\(p_trip_id\) then raise exception.*journey_read_only/i)
  assert.match(sql, /memo references an unknown activity/i)
  assert.match(sql, /memo content exceeds 2000 characters/i)
  assert.doesNotMatch(sql, /tripbook_save_journey_memo\([^)]*updatedBy/i)
})

